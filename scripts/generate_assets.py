#!/usr/bin/env python3
"""Generate our original, watertight lathed ceramic vessel (no external asset)."""
import math
from pathlib import Path
# Closed cross section: exterior, lip, interior, then bottom; axis rings become caps.
profile=[(0.0,0.03),(.30,.03),(.40,.09),(.47,.27),(.49,.50),(.45,.78),(.34,1.02),(.25,1.18),(.24,1.34),(.25,1.40),(.21,1.40),(.20,1.33),(.21,1.18),(.30,1.01),(.41,.77),(.45,.50),(.43,.28),(.36,.14),(0.0,.14)]
n=96
vertices=[]
for r,y in profile:
 for i in range(n):
  a=i*math.tau/n;vertices.append((r*math.cos(a),y,r*math.sin(a)))
lines=['# Original Lumen vessel, generated by scripts/generate_assets.py']
lines.extend('v %.7f %.7f %.7f'%v for v in vertices)
# Profile tangent yields outward normals, including the hollow interior.
for j,(r,y) in enumerate(profile):
 before=profile[max(0,j-1)];after=profile[min(len(profile)-1,j+1)]
 dr=after[0]-before[0];dy=after[1]-before[1];length=math.hypot(dr,dy)
 for i in range(n):
  a=i*math.tau/n;lines.append('vn %.7f %.7f %.7f'%(dy*math.cos(a)/length,-dr/length,dy*math.sin(a)/length))
for j in range(len(profile)-1):
 for i in range(n):
  a=j*n+i+1;b=j*n+(i+1)%n+1;c=(j+1)*n+(i+1)%n+1;d=(j+1)*n+i+1
  # Winding agrees with normals: angular tangent x profile tangent points inward, reverse it.
  if profile[j][0]>0:lines.append(f'f {a}//{a} {d}//{d} {b}//{b}')
  if profile[j+1][0]>0:lines.append(f'f {b}//{b} {d}//{d} {c}//{c}')
Path(__file__).resolve().parent.parent.joinpath('assets/vessel.obj').write_text('\n'.join(lines)+'\n')
